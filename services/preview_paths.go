package services

import (
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"strings"

	"iofabrik/internal/ldsdkprotocol"
)

const previewAttributes = "# Preserve generated bytes while retaining text comparisons.\n.gitattributes -text -eol -filter -working-tree-encoding -ident diff\nRSLogix5000Content/** -text -eol -filter -working-tree-encoding -ident diff\n"

type previewContext struct {
	Root          string
	GitDir        string
	CommonDir     string
	RootID        string
	GitID         string
	CommonID      string
	ParentID      string
	DestinationID string
	Destination   string
	Revision      string
	IndexHash     string
}

func eligiblePreviewName(name string) bool {
	parts := strings.Split(name, ".")
	return len(parts) == 2 && parts[0] != "" && strings.EqualFold(parts[1], "acd") && !strings.ContainsAny(name, "\r\n")
}

func previewWithin(root, path string) bool {
	rel, err := filepath.Rel(root, path)
	return err == nil && rel != "." && rel != ".." && !strings.HasPrefix(rel, ".."+string(filepath.Separator)) && !filepath.IsAbs(rel)
}

func capturePreviewContext(runner *CommandRunner, root, destination string) (previewContext, error) {
	c := previewContext{Root: root, Destination: destination}
	var err error
	if err = previewPhysicalPath(root); err != nil {
		return c, err
	}
	if err = previewPhysicalPath(filepath.Dir(destination)); err != nil {
		return c, err
	}
	if c.GitDir, err = gitDirPath(runner, root); err != nil {
		return c, err
	}
	if c.CommonDir, err = gitCommonDirPath(runner, root); err != nil {
		return c, err
	}
	if err = previewPhysicalPath(c.GitDir); err != nil {
		return c, err
	}
	if err = previewPhysicalPath(c.CommonDir); err != nil {
		return c, err
	}
	if c.RootID, err = previewFileIdentity(root); err != nil {
		return c, err
	}
	if c.GitID, err = previewFileIdentity(c.GitDir); err != nil {
		return c, err
	}
	if c.CommonID, err = previewFileIdentity(c.CommonDir); err != nil {
		return c, err
	}
	if c.ParentID, err = previewFileIdentity(filepath.Dir(destination)); err != nil {
		return c, err
	}
	if c.DestinationID, err = previewFileIdentity(destination); err != nil && !os.IsNotExist(err) {
		return c, err
	}
	head := runner.RunGit(root, "rev-parse", "--verify", "HEAD")
	branch := runner.RunGit(root, "symbolic-ref", "-q", "HEAD")
	c.Revision = strings.TrimSpace(head.Stdout) + "\x00" + strings.TrimSpace(branch.Stdout)
	index, err := gitAdminPath(runner, root, "index")
	if err != nil {
		return c, err
	}
	c.IndexHash, err = previewHashFile(index)
	if os.IsNotExist(err) {
		err = nil
	}
	return c, err
}

func validatePreviewDestination(path string) error {
	info, err := os.Lstat(path)
	if os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		return err
	}
	if !info.IsDir() {
		return fmt.Errorf("destination is not a folder")
	}
	if err := previewPhysicalPath(path); err != nil {
		return err
	}
	entries, err := os.ReadDir(path)
	if err != nil {
		return err
	}
	if len(entries) == 0 {
		return nil
	}
	if err := ldsdkprotocol.ValidateContent(filepath.Join(path, "RSLogix5000Content")); err != nil {
		return err
	}
	if attrs, err := os.ReadFile(filepath.Join(path, ".gitattributes")); err == nil && string(attrs) != previewAttributes {
		return fmt.Errorf("destination has custom attributes")
	} else if err != nil && !os.IsNotExist(err) {
		return err
	}
	return filepath.WalkDir(path, func(p string, entry os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if !entry.IsDir() && !entry.Type().IsRegular() {
			return fmt.Errorf("destination contains a linked or special file")
		}
		return previewPhysicalPath(p)
	})
}

func previewHashFile(path string) (string, error) {
	file, err := os.Open(path)
	if err != nil {
		return "", err
	}
	defer file.Close()
	h := sha256.New()
	if _, err := io.Copy(h, file); err != nil {
		return "", err
	}
	return hex.EncodeToString(h.Sum(nil)), nil
}

func copyPreviewTree(source, target string) error {
	if err := previewPhysicalPath(source); err != nil {
		return err
	}
	return filepath.WalkDir(source, func(path string, entry os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if err := previewPhysicalPath(path); err != nil {
			return err
		}
		rel, err := filepath.Rel(source, path)
		if err != nil {
			return err
		}
		dest := filepath.Join(target, rel)
		if entry.IsDir() {
			return os.MkdirAll(dest, 0700)
		}
		if !entry.Type().IsRegular() {
			return fmt.Errorf("not a regular generated file")
		}
		return copyFile(path, dest)
	})
}
